"""
CAN-Sentinel: one-command retraining on the official normal recordings.

When the team's official normal runs arrive, this runs every step in order and
stops early if the data is not clean:

  1. Rolling-counter check on every run (normal runs must have 0 breaks)
  2. Timestamp check (no backward steps, no gaps over 1 s)
  3. Feature extraction for each run (saved as data/features_<name>.csv)
  4. Training on the training runs only
  5. Detector on the held-out test run: every alert there is a false alarm
  6. A Markdown report of all the above

Usage (from the repository root):
    python ml_engine/retrain.py --train data/normal_run1_1101.csv data/normal_run2_1101.csv \
        --test data/normal_run3_1101.csv --report docs/retrain_report.md

Author: Abinaya Francisca EP (Team Lead)
"""

import argparse
import os
import sys
import tempfile

import pandas as pd

from counter_check import check as counter_check
from detect import run as run_detector
from evaluate_alerts import read_alerts
from features import extract_features, load_frames
from train_model import MODEL_PATH, train

MAX_GAP_SECONDS = 1.0


def check_run(path):
    """Counter and timestamp checks on one recording; returns a result row."""
    raw = pd.read_csv(path)
    backward = int((raw["timestamp"].diff().dropna() < 0).sum())
    frames = load_frames(path)
    gaps = frames["timestamp"].diff().dropna()
    summary, _ = counter_check(raw)
    breaks = int(summary["breaks"].sum()) if not summary.empty else None
    ranges = ", ".join(sorted(set(summary["range"]))) if not summary.empty else "-"
    duration = float(frames["timestamp"].max() - frames["timestamp"].min())
    return {
        "file": path, "frames": len(frames), "minutes": round(duration / 60, 1),
        "fps": round(len(frames) / duration, 1) if duration else 0,
        "ids": frames["can_id"].nunique(), "counter_breaks": breaks, "counter_range": ranges,
        "backward_steps": backward, "max_gap_s": round(float(gaps.max()), 3) if len(gaps) else 0,
    }


def feature_path(path):
    name = os.path.splitext(os.path.basename(path))[0]
    return os.path.join(os.path.dirname(path) or ".", f"features_{name}.csv")


def main():
    p = argparse.ArgumentParser(description="CAN-Sentinel retraining pipeline")
    p.add_argument("--train", nargs="+", required=True, help="normal runs to train on")
    p.add_argument("--test", required=True, help="held-out normal run for false-alarm testing")
    p.add_argument("--model", default=MODEL_PATH)
    p.add_argument("--report", help="write a Markdown report here")
    p.add_argument("--force", action="store_true", help="continue even if a data check fails")
    a = p.parse_args()

    runs = a.train + [a.test]
    print("Step 1-2: data checks")
    checks = [check_run(r) for r in runs]
    table = pd.DataFrame(checks)
    print(table.to_string(index=False))
    problems = [c["file"] for c in checks
                if c["counter_breaks"] or c["backward_steps"] or c["max_gap_s"] > MAX_GAP_SECONDS]
    if problems and not a.force:
        sys.exit(f"\nData check failed for: {', '.join(problems)}\n"
                 "Normal runs must have 0 counter breaks, no backward timestamps and no gap over 1 s. "
                 "Fix the recording, or rerun with --force to continue anyway.")

    print("\nStep 3: feature extraction")
    feature_files = []
    for r in a.train:
        out = feature_path(r)
        features = extract_features(load_frames(r))
        features.to_csv(out, index=False)
        feature_files.append(out)
        print(f"  {r} -> {out} ({len(features)} windows)")

    print("\nStep 4: training")
    train(feature_files, a.model)

    print("\nStep 5: detector on the held-out run")
    alert_file = os.path.join(tempfile.gettempdir(), "can_sentinel_retrain_alerts.jsonl")
    run_detector(a.test, alert_file, model_path=a.model)
    alerts = read_alerts(alert_file)
    test_minutes = checks[-1]["minutes"]
    per_hour = round(len(alerts) / (test_minutes / 60), 1) if test_minutes else None
    print(f"False alarms on {a.test}: {len(alerts)} ({per_hour} per hour)")

    if a.report:
        lines = ["# CAN-Sentinel: Retraining Report", "",
                 "Generated by `ml_engine/retrain.py`.", "",
                 "## Data checks", "",
                 "| File | Frames | Minutes | Frames/s | IDs | Counter breaks | Counter range | Backward steps | Max gap (s) |",
                 "|---|---:|---:|---:|---:|---:|---|---:|---:|"]
        for c in checks:
            lines.append(f"| `{c['file']}` | {c['frames']} | {c['minutes']} | {c['fps']} | {c['ids']} | "
                         f"{c['counter_breaks']} | {c['counter_range']} | {c['backward_steps']} | {c['max_gap_s']} |")
        lines += ["", "## Training", "",
                  f"Trained on: {', '.join(f'`{f}`' for f in a.train)}", "",
                  "## False alarms on the held-out run", "",
                  f"`{a.test}`: {len(alerts)} alerts in {test_minutes} minutes "
                  f"({per_hour} per hour). Every alert on a normal run is a false alarm."]
        if alerts:
            kinds = pd.Series([x["attack_type"] for x in alerts]).value_counts()
            lines += ["", "| Alert type | Count |", "|---|---:|"]
            lines += [f"| {k} | {v} |" for k, v in kinds.items()]
        with open(a.report, "w") as f:
            f.write("\n".join(lines) + "\n")
        print(f"\nReport written to {a.report}")


if __name__ == "__main__":
    main()
